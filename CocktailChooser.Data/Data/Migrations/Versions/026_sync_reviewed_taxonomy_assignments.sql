    c.Id,
    t.Id,
    strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
FROM _desired_taxonomy_assignments d
INNER JOIN Cocktails c ON c.CanonicalKey = d.CanonicalKey
INNER JOIN TagTypes tt ON tt.Name = d.TagTypeName
